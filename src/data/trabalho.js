export function trabalhoDe(id) {
  const d = T[id]
  let label = 'profissional'
  try {
    label = getProfissao(id)?.label || label
  } catch {}
  if (!d) {
    return {
      persona: `Você é um(a) ${label.toLowerCase()} experiente e ajuda colegas da área com dicas práticas, cálculos, organização e boas práticas.`,
      perguntas: [
        `Dicas para ser um(a) ${label.toLowerCase()} melhor`,
        'Organize minhas tarefas de hoje',
        'Como calcular o preço do meu serviço?',
        'Escreva uma mensagem profissional para um cliente',
      ],
      checklist: {
        titulo: 'Rotina de trabalho',
        itens: [
          'Planejar o dia',
          'Separar materiais',
          'Atender e registrar',
          'Organizar o local',
          'Revisar pendências',
        ],
      },
    }
  }
  const [persona, perguntas, titulo, itens] = d
  return {
    persona,
    perguntas,
    checklist: {
      titulo,
      itens,
    },
  }
}
