function distKm(a, b) {
  const rad = x => (x * Math.PI) / 180
  const dLat = rad(b.lat - a.lat)
  const dLng = rad(b.lng - a.lng)
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLng / 2) ** 2
  return 2 * 6371 * Math.asin(Math.sqrt(h))
}
export function sistemaEm(p) {
  if (!p || p.lat == null || p.lng == null) return null
  let melhor = null
  for (const s of SISTEMAS) {
    const d = distKm(p, s.centro)
    if (d <= s.raioKm && (!melhor || d < melhor.d))
      melhor = {
        s,
        d,
      }
  }
  return melhor ? melhor.s : null
}
export function todasEstacoes(sistema) {
  if (!sistema) return []
  return sistema.linhas.flatMap(linha =>
    linha.estacoes.map((est, idx) => ({
      ...est,
      idx,
      linha,
    })),
  )
}
export function pontosDoSistema(sistema) {
  return sistema ? sistema.linhas.flatMap(l => l.estacoes.map(est => [est.lat, est.lng])) : []
}
